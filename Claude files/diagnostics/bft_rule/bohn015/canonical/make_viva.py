HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
SRC = ROOT.parent / "QUANTITATIVE_MODEL" / "results" / "GLOBAL_2026-11-13_bohn015" / "headline.json"
OUT = HERE / "viva"
OUT.mkdir(exist_ok=True)
d = json.load(open(SRC))
NOPOL, RULE = "#7a7a7a", "#1f5fa8"


def f(x, nd=2):
    s = f"{x:+.{nd}f}" if abs(x) >= 0.5 * 10 ** -nd else f"{0:.{nd}f}"
    return s.replace("-", "$-$")


def cell(dec, part, key, nd):
    e, t = dec["exact"][part][key], dec["two_quarter"][part][key]
    return f"{f(e, nd)} ({f(t, nd)})"


ROWS = [("Sovereign spread (bp)", "sov_bp", 0), ("$D$ bond price $q^D_t$ (\\%)", "Q_bD", 2),
        ("$D$ bank net worth $n_{D,t}$ (\\%)", "n", 1), ("Multiplier $\\mu_{D,t}$", "mu", 3),
        ("Lending spread $r^{wc}_{D,t}-r_{D,t}$ (bp)", "ls_bp", 0), ("Investment $I_{D,t}$ (\\%)", "I", 2),
        ("Output $Y_{D,t}$ (\\%)", "Y", 3), ("Purchases (\\% of s.s.\\ $D$ debt)", "m_pct", 2),
        ("Consumption $C_{D,t}/C_{F,t}$ (\\%)", "CD_over_CF", 3)]


def impact_table():
    lines = [r"% PROVISIONAL (2026-11-13). Generated by make_viva.py from headline.json; do not hand-edit.",
             r"\begin{table}[htbp]", r"\centering",
             r"\caption{Impact of a sovereign-risk shock: no backstop and the announced proportional rule}",
             r"\label{tab:headline-impact}", r"\small", r"\begin{tabular}{lccc}", r"\toprule",
             r" & No backstop & Announced rule & Effect of the rule \\", r"\midrule"]
    for pd, lab in (("0.02", "2\\%"), ("0.015", "1.5\\%")):
        lines.append(rf"\multicolumn{{4}}{{l}}{{\emph{{Default probability {lab} a quarter}}}} \\")
        dec = {m: d["decomposition"][f"{m}_{pd}"] for m in ("exact", "two_quarter")}
        for lab_r, k, nd in ROWS:
            lines.append(f"{lab_r} & {cell(dec, 'no_policy_response', k, nd)} & "
                         f"{cell(dec, 'policy_response', k, nd)} & {cell(dec, 'incremental', k, nd)} \\\\")
        if pd == "0.02":
            lines.append(r"\midrule")
    ann = {m: d["decomposition"][f"{m}_0.02"]["announcement"] for m in ("exact", "two_quarter")}
    lines += [r"\midrule", r"\multicolumn{4}{l}{\emph{Announcement at the rest point (rule against no backstop)}} \\"]
    for lab_r, k, nd in (("Sovereign spread (bp)", "sov_bp", 1), ("Output $Y_{D,t}$ (\\%)", "Y", 3),
                         ("Investment $I_{D,t}$ (\\%)", "I", 2), ("$D$ bank net worth $n_{D,t}$ (\\%)", "n", 2)):
        lines.append(f"{lab_r} & & & {f(ann['exact'][k], nd)} ({f(ann['two_quarter'][k], nd)}) \\\\")
    th = {a: d[a]["threshold"] for a in ("off", "pol")}
    lines += [r"\bottomrule", r"\end{tabular}", r"\par\medskip", r"\begin{minipage}{0.95\linewidth}\footnotesize",
              r"\emph{Notes:} impact quarter, each economy measured from its own stochastic rest point; "
              r"quantities and prices in percent, rates in bp a year, $\mu_{D,t}$ in levels. The effect of the rule is "
              r"the rule's response less the no-backstop response; it excludes the announcement effect, reported "
              r"separately. Purchases are the face value bought in the impact quarter over the steady-state $D$ "
              r"debt. Each cell clears the impact quarter exactly with next quarter's values from the fitted decision "
              r"rules; in parentheses, the impact and the following quarter are cleared jointly. "
              f"Bohn coefficient {d['settings']['bohn']:.2f}; the rule's coefficient $k=2$. The constraint binds "
              f"from a default probability of {100 * th['off']['exact']['pd']:.2f}\\% "
              f"({100 * th['off']['2q']['pd']:.2f}\\%) without a backstop and "
              f"{100 * th['pol']['exact']['pd']:.2f}\\% ({100 * th['pol']['2q']['pd']:.2f}\\%) under the rule.",
              r"\end{minipage}", r"\end{table}"]
    (OUT / "tab_headline_impact.tex").write_text("\n".join(lines) + "\n")


def validation_table():
    # validated identities against approximation-dependent quantities
    gaps = []
    for a in ("off", "pol"):
        gaps.append(d[a]["rest"]["identities"])
        for pd, v in d[a]["impact"].items():
            gaps.append(v["identities"])
            if "identities_2q" in v:
                gaps.append(v["identities_2q"])
    worst = {k: max(abs(g[k]) for g in gaps) for k in gaps[0]}
    names = dict(net_worth="Net worth = returns on capital, bonds and claim less deposits, plus start-up funds",
                 bond_market="$D$ bonds issued = held by $D$ banks, $F$ banks and the Eurosystem",
                 multiplier="$\\mu_{D,t}=\\max\\{\\psi_{D,t},0\\}$ at the cleared allocation",
                 lending_spread="Lending spread $=\\lambda_K\\mu_{D,t}/\\E_t[\\Omega_{D,t,t+1}]$",
                 cb_claim="Eurosystem claim = market value of its book",
                 goods_F="$F$ goods market (implied by Walras' law)",
                 book_runoff="Book = run-off of last quarter's book + purchase")
    # off-grid errors on the exactly cleared simulation (accuracy_exact.py): the fitted simulation pushes the book
    # below zero at once, where the rule switches itself off
    acc = json.load(open(SRC.with_name("accuracy_exact.json")))
    ca = d["pol"]["cont_accuracy"]["0.02"]["reg0"]
    rep = d["reproduction"]
    lines = [r"% PROVISIONAL (2026-11-13). Generated by make_viva.py from headline.json; do not hand-edit.",
             r"\begin{table}[htbp]", r"\centering", r"\caption{What is exact and what depends on the approximation}",
             r"\label{tab:headline-validation}", r"\small", r"\begin{tabular}{lr}", r"\toprule",
             r"\multicolumn{2}{l}{\emph{Accounting identities (largest absolute gap over every reported state)}} \\"]
    lines += [f"{names[k]} & {worst[k]:.0e} \\\\" for k in names]
    lines += [r"\midrule", r"\multicolumn{2}{l}{\emph{Solution accuracy (simulation cleared exactly each quarter, 1,200 quarters)}} \\",
              f"Equilibrium conditions at the grid points, announced rule & "
              f"{d['settings']['solve_k2']['worst']:.0e} \\\\",
              f"Mean / max $\\log_{{10}}$ Euler error off the grid, no backstop & {acc['off']['l10_mean']:.1f} / "
              f"{acc['off']['l10_max']:.1f} \\\\",
              f"Mean / max $\\log_{{10}}$ Euler error off the grid, announced rule & {acc['pol']['l10_mean']:.1f} / "
              f"{acc['pol']['l10_max']:.1f} \\\\",
              f"Fitted next-quarter franchise value, largest error at the 2\\% shock (\\%) & "
              f"{100 * ca['alpha_D']:.1f} \\\\",
              f"Eurosystem book on the simulated ergodic set (\\% of debt, min / max) & "
              f"{acc['pol']['book_min_pct']:.3f} / {acc['pol']['book_max_pct']:.2f} \\\\",
              f"Simulated quarters in which the constraint binds, no backstop / rule (\\%) & "
              f"{100 * acc['off']['share_binding']:.1f} / {100 * acc['pol']['share_binding']:.1f} \\\\",
              f"Largest gap to the diagnostic solutions of the same calibration (relative) & "
              f"{max(rep['off']['max_rel_gap'], rep['pol']['max_rel_gap']):.0e} \\\\",
              r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (OUT / "tab_headline_validation.tex").write_text("\n".join(lines) + "\n")


CAPTIONS = {
    "fig_irf_2pct": "A 2% quarterly default probability: without a backstop the D banks' constraint binds and credit "
                    "and investment fall on impact; the announced rule keeps the constraint (almost) slack with "
                    "purchases of 1.4% of the debt, and its effect on the sovereign spread is small. Lines clear each "
                    "quarter exactly; hollow markers are the impact values when two quarters are cleared jointly.",
    "fig_irf_15pct": "The lower-stress 1.5% shock: the constraint barely binds without a backstop, so the rule's "
                     "gain is smaller; it removes the whole lending spread under either clearing.",
    "fig_threshold": "Impact lending spread against the default probability: the rule moves the binding threshold "
                     "from about 1.3% to 1.9-2.4%, which places the 2% headline shock at the policy economy's "
                     "threshold; whether a residual spread survives there depends on the clearing method.",
}


def save(fig, name):
    fig.savefig(OUT / f"{name}.pdf", bbox_inches="tight")
    chars = int(fig.get_size_inches()[0] * 14)
    fig.text(0.5, -0.02, textwrap.fill(CAPTIONS[name], width=chars), ha="center", va="top", fontsize=8,
             style="italic", color="0.35")
    fig.savefig(OUT / f"{name}.png", bbox_inches="tight", dpi=300)
    plt.close(fig)


PANELS = [("Y", "Output $Y_D$", "% dev."), ("I", "Investment $I_D$", "% dev."),
          ("spread", "Lending spread $r^{wc}_D-r_D$", "bp a year"), ("sov_bp", "Sovereign spread", "bp a year"),
          ("n", "$D$ bank net worth $n_D$", "% dev."), ("m_cb", "Purchases", "% of s.s. $D$ debt")]
TWOQ = dict(Y=("Y", "pct"), I=("I", "pct"), spread=("ls_bp", "lvl"), sov_bp=("sov_bp", "abs"), n=("n", "pct"),
            m_cb=("m_pct", "abs"))


def irf_fig(pd, name):
    fig, axs = plt.subplots(2, 3, figsize=(9.0, 5.2))
    T = 21
    for ax, (k, title, unit) in zip(axs.flat, PANELS):
        for arm, col, lab in (("off", NOPOL, "No backstop"), ("pol", RULE, "Announced rule")):
            y = np.asarray(d[arm]["irf"][pd][k][:T], dtype=float)
            ax.plot(range(len(y)), y, color=col, lw=1.8, label=lab)
            key, kind = TWOQ[k]
            r2, s2 = d[arm]["rest"]["two_quarter"], d[arm]["impact"][pd]["two_quarter"]
            v = (100 * (s2[key] / r2[key] - 1) if kind == "pct" else s2[key] - r2[key] if kind == "lvl"
                 else s2[key] if k == "m_cb" else s2[key])
            ax.plot([0], [v], marker="o", mfc="none", mec=col, ms=6, ls="none")
        ax.axhline(0, color="0.8", lw=0.6)
        ax.set_title(title, fontsize=9)
        ax.set_ylabel(unit, fontsize=8)
        ax.tick_params(labelsize=7)
        ax.spines[["top", "right"]].set_visible(False)
    for ax in axs[1]:
        ax.set_xlabel("quarters", fontsize=8)
    axs[0, 0].legend(fontsize=7, frameon=False)
    fig.tight_layout()
    save(fig, name)


def threshold_fig():
    fig, ax = plt.subplots(figsize=(5.4, 3.4))
    for arm, col, lab in (("off", NOPOL, "No backstop"), ("pol", RULE, "Announced rule")):
        sc = d[arm]["scan"]
        x = np.array([float(p) for p in sc]) * 100
        y = np.array([sc[p]["ls_bp"] for p in sc])
        o = np.argsort(x)
        ax.plot(x[o], y[o], color=col, lw=1.8, marker="o", ms=3, label=lab)
        for m, ls in (("exact", "-"), ("2q", ":")):
            t = d[arm]["threshold"][m]["pd"]
            if t:
                ax.axvline(100 * t, color=col, lw=0.8, ls=ls, alpha=0.7)
    for p, lab in ((1.5, "comparison"), (2.0, "headline")):
        ax.axvspan(p - 0.01, p + 0.01, color="0.85")
        ax.text(p + 0.03, 300, lab, fontsize=7, color="0.4")
    ax.set_xlim(1.0, 4.0)
    ax.set_ylim(-5, 340)
    ax.set_xlabel("default probability, % a quarter", fontsize=8)
    ax.set_ylabel("impact lending spread, bp a year", fontsize=8)
    ax.tick_params(labelsize=7)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=7, frameon=False, title="thresholds: solid one-quarter, dotted two-quarter", title_fontsize=6)
    fig.tight_layout()
    save(fig, "fig_threshold")


